-- Portable SQL: runs on PostgreSQL and on H2 in PostgreSQL mode.

create table app_user (
    id            bigint generated by default as identity primary key,
    email         varchar(255) not null unique,
    password_hash varchar(100) not null,
    full_name     varchar(150) not null,
    role          varchar(20)  not null,
    enabled       boolean      not null default true,
    created_at    timestamp with time zone not null
);

create table product (
    id               bigint generated by default as identity primary key,
    sku              varchar(40)   not null unique,
    name             varchar(200)  not null,
    description      varchar(2000),
    unit_price       numeric(12, 2) not null,
    quantity_on_hand integer       not null default 0,
    reorder_level    integer       not null default 0,
    active           boolean       not null default true,
    version          bigint        not null default 0,
    created_at       timestamp with time zone not null,
    updated_at       timestamp with time zone not null,
    constraint chk_product_quantity_non_negative check (quantity_on_hand >= 0),
    constraint chk_product_price_non_negative check (unit_price >= 0)
);

create table stock_movement (
    id              bigint generated by default as identity primary key,
    product_id      bigint       not null references product (id),
    movement_type   varchar(30)  not null,
    quantity_change integer      not null,
    quantity_after  integer      not null,
    reference       varchar(100),
    note            varchar(500),
    created_by      varchar(255) not null,
    created_at      timestamp with time zone not null
);

create index idx_stock_movement_product on stock_movement (product_id, created_at);

create table sales_order (
    id            bigint generated by default as identity primary key,
    order_number  varchar(20) unique,
    customer_name varchar(200)   not null,
    status        varchar(20)    not null,
    total_amount  numeric(14, 2) not null,
    created_by    varchar(255)   not null,
    version       bigint         not null default 0,
    created_at    timestamp with time zone not null,
    updated_at    timestamp with time zone not null,
    confirmed_at  timestamp with time zone,
    shipped_at    timestamp with time zone,
    cancelled_at  timestamp with time zone
);

create index idx_sales_order_status on sales_order (status);

create table order_line (
    id         bigint generated by default as identity primary key,
    order_id   bigint         not null references sales_order (id),
    product_id bigint         not null references product (id),
    quantity   integer        not null,
    unit_price numeric(12, 2) not null,
    line_total numeric(14, 2) not null,
    constraint chk_order_line_quantity_positive check (quantity > 0)
);

create index idx_order_line_order on order_line (order_id);
